create or replace function public.audit_case_viber_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.viber_shared_at is distinct from old.viber_shared_at then
    perform public.record_privileged_audit_event(
      case when new.viber_shared_at is null then 'viber_marked_not_sent' else 'viber_marked_sent' end,
      'case',
      new.id::text,
      jsonb_build_object('sent', new.viber_shared_at is not null)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_audit_case_viber_status on public.cases;
create trigger trg_audit_case_viber_status
after update of viber_shared_at on public.cases
for each row execute function public.audit_case_viber_status();

create or replace function public.audit_case_share_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  audit_action text;
begin
  if tg_op = 'INSERT' then
    audit_action := 'case_share_created';
  elsif new.is_active = false and old.is_active = true then
    audit_action := 'case_share_revoked';
  elsif new.public_token is distinct from old.public_token then
    audit_action := 'case_share_regenerated';
  elsif new.is_active = true and old.is_active = false then
    audit_action := 'case_share_created';
  else
    return new;
  end if;

  perform public.record_privileged_audit_event(
    audit_action,
    'case',
    new.case_id::text,
    jsonb_build_object('active', new.is_active)
  );
  return new;
end;
$$;

drop trigger if exists trg_audit_case_share_change on public.case_shares;
create trigger trg_audit_case_share_change
after insert or update on public.case_shares
for each row execute function public.audit_case_share_change();

create or replace function public.list_privileged_audit_events(
  p_limit integer default 30,
  p_before timestamptz default null
)
returns table (
  id bigint,
  actor_id uuid,
  actor_name text,
  action text,
  target_type text,
  target_id text,
  metadata jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
stable
as $$
begin
  if not public.current_user_has_any_role(array['admin', 'moderator', 'training_officer']) then
    raise exception 'Only authorized staff can view audit events.';
  end if;

  return query
  select
    events.id,
    events.actor_id,
    coalesce(profiles.nickname, profiles.full_name, 'System') as actor_name,
    events.action,
    events.target_type,
    events.target_id,
    events.metadata,
    events.created_at
  from public.privileged_audit_events events
  left join public.profiles profiles on profiles.id = events.actor_id
  where p_before is null or events.created_at < p_before
  order by events.created_at desc, events.id desc
  limit least(greatest(coalesce(p_limit, 30), 1), 100);
end;
$$;

revoke all on function public.list_privileged_audit_events(integer, timestamptz) from public, anon;
grant execute on function public.list_privileged_audit_events(integer, timestamptz) to authenticated;

commit;
