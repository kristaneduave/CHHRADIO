begin;

create table if not exists public.privileged_audit_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  constraint privileged_audit_events_safe_metadata check (
    metadata - array['status', 'requested_role', 'old_role', 'new_role', 'old_status', 'new_status', 'role', 'submission_type', 'sent', 'active'] = '{}'::jsonb
  )
);

create index if not exists idx_privileged_audit_events_created_at
  on public.privileged_audit_events (created_at desc, id desc);

alter table public.privileged_audit_events enable row level security;
revoke insert, update, delete on public.privileged_audit_events from anon, authenticated;

drop policy if exists "privileged_audit_events_staff_read" on public.privileged_audit_events;
create policy "privileged_audit_events_staff_read"
on public.privileged_audit_events
for select
to authenticated
using (public.current_user_has_any_role(array['admin', 'moderator', 'training_officer']));

create or replace function public.record_privileged_audit_event(
  p_action text,
  p_target_type text,
  p_target_id text,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.privileged_audit_events (actor_id, action, target_type, target_id, metadata)
  values (auth.uid(), p_action, p_target_type, nullif(p_target_id, ''), coalesce(p_metadata, '{}'::jsonb));
end;
$$;

revoke all on function public.record_privileged_audit_event(text, text, text, jsonb) from public, anon, authenticated;

create or replace function public.audit_access_request_review()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status and new.status in ('approved', 'rejected') then
    perform public.record_privileged_audit_event(
      'access_request_' || new.status,
      'account_access_request',
      new.id::text,
      jsonb_build_object('status', new.status, 'requested_role', new.requested_role)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_audit_access_request_review on public.account_access_requests;
create trigger trg_audit_access_request_review
after update of status on public.account_access_requests
for each row execute function public.audit_access_request_review();

create or replace function public.audit_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role is distinct from old.role then
    perform public.record_privileged_audit_event(
      'primary_role_changed',
      'profile',
      new.id::text,
      jsonb_build_object('old_role', old.role, 'new_role', new.role)
    );
  end if;

  if (to_jsonb(new) ->> 'account_status') is distinct from (to_jsonb(old) ->> 'account_status') then
    perform public.record_privileged_audit_event(
      'account_status_changed',
      'profile',
      new.id::text,
      jsonb_build_object(
        'old_status', to_jsonb(old) ->> 'account_status',
        'new_status', to_jsonb(new) ->> 'account_status'
      )
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_audit_profile_role_change on public.profiles;
create trigger trg_audit_profile_role_change
after update on public.profiles
for each row execute function public.audit_profile_role_change();

create or replace function public.audit_user_role_assignment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  affected_user_id uuid;
  affected_role text;
begin
  if tg_op = 'INSERT' then
    affected_user_id := new.user_id;
    affected_role := new.role;
  else
    affected_user_id := old.user_id;
    affected_role := old.role;
  end if;

  perform public.record_privileged_audit_event(
    case when tg_op = 'INSERT' then 'role_assigned' else 'role_removed' end,
    'profile',
    affected_user_id::text,
    jsonb_build_object('role', affected_role)
  );
  if tg_op = 'INSERT' then
    return new;
  end if;
  return old;
end;
$$;

drop trigger if exists trg_audit_user_role_assignment on public.user_roles;
create trigger trg_audit_user_role_assignment
after insert or delete on public.user_roles
for each row execute function public.audit_user_role_assignment();

